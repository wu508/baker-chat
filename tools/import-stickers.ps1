# Import stickers from the asset zip, downscale to 64x64, and regenerate Stickers.java
# Usage: powershell -ExecutionPolicy Bypass -File tools\import-stickers.ps1 -ZipPath "D:\path\to\assets.zip"
param([string]$ZipPath = "")

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName System.IO.Compression.FileSystem

$root = Split-Path -Parent $PSScriptRoot
$dst  = Join-Path $root 'src\main\resources\assets\baker\textures\ui\sticker'
$java = Join-Path $root 'src\main\java\dev\wanye\bakerchat\ui\Stickers.java'
New-Item -ItemType Directory -Force -Path $dst | Out-Null

if (-not $ZipPath -or -not (Test-Path $ZipPath)) {
    Write-Warning "zip not found, keeping existing stickers"
    return
}

$archive = [System.IO.Compression.ZipFile]::OpenRead($ZipPath)
$entries = $archive.Entries | Where-Object { $_.Name -like 'sns_sticker*.png' } | Sort-Object Name
$names = @()

foreach ($entry in $entries) {
    $stem = [System.IO.Path]::GetFileNameWithoutExtension($entry.Name).ToLower()
    $stem = [regex]::Replace($stem, '[^a-z0-9_\-]', '_')

    $out = Join-Path $dst ($stem + '.png')
    $tmp = Join-Path $env:TEMP ('sticker_' + $stem + '.png')
    [System.IO.Compression.ZipFileExtensions]::ExtractToFile($entry, $tmp, $true)

    $img = [System.Drawing.Image]::FromFile($tmp)
    $bmp = New-Object System.Drawing.Bitmap(64, 64, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $g.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality
    $g.Clear([System.Drawing.Color]::Transparent)
    $g.DrawImage($img, 0, 0, 64, 64)
    $g.Dispose()
    $bmp.Save($out, [System.Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
    $img.Dispose()
    Remove-Item $tmp -ErrorAction SilentlyContinue

    $names += $stem
}

$archive.Dispose()

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('package dev.wanye.bakerchat.ui;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('import net.minecraft.util.Identifier;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/** Sticker list, generated by tools/import-stickers.ps1. */')
[void]$sb.AppendLine('public final class Stickers {')
[void]$sb.AppendLine('    public static final String[] NAMES = {')
for ($i = 0; $i -lt $names.Count; $i++) {
    $sep = if ($i -lt $names.Count - 1) { ',' } else { '' }
    [void]$sb.AppendLine(('            "' + $names[$i] + '"' + $sep))
}
[void]$sb.AppendLine('    };')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    private Stickers() {')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    public static Identifier texture(String name) {')
[void]$sb.AppendLine('        return new Identifier("baker", "textures/ui/sticker/" + name + ".png");')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')

[System.IO.File]::WriteAllText($java, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

"stickers: {0}, total {1:N0} KB" -f $names.Count, ((Get-ChildItem $dst | Measure-Object Length -Sum).Sum / 1KB)
